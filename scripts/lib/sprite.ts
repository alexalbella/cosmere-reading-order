import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

/** The drawings that become symbols: one emblem per world, one icon per format and per status. */
const SYMBOL_FILE = /^(emblem|format|status)-[a-z-]+\.svg$/
/** The root attributes a symbol keeps, so `currentColor`, strokes and caps reach every shape. */
const KEPT = ['viewBox', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin']

export interface SpriteSource {
  name: string
  svg: string
}

/** Every symbol drawing of a folder, in name order. */
export function spriteSources(dir: string): SpriteSource[] {
  return readdirSync(dir)
    .filter((f) => SYMBOL_FILE.test(f))
    .sort()
    .map((f) => ({ name: f.replace(/\.svg$/, ''), svg: readFileSync(join(dir, f), 'utf8') }))
}

function symbol({ name, svg }: SpriteSource): string {
  const root = /<svg\b([^>]*)>([\s\S]*)<\/svg>/.exec(svg)
  if (!root) throw new Error(`NOT_SVG ${name}`)
  const [, attrs, body] = root
  const kept = KEPT.flatMap((key) => {
    const m = new RegExp(`\\s${key}="([^"]*)"`).exec(attrs!)
    return m ? [`${key}="${m[1]}"`] : []
  })
  const inner = body!
    .replace(/<!--[\s\S]*?-->/g, '')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => `      ${line}`)
    .join('\n')
  return `    <symbol id="${name}" ${kept.join(' ')}>\n${inner}\n    </symbol>`
}

/** The single-file component that holds every symbol, hidden, for `<use href="#name">`. */
export function buildSprite(sources: SpriteSource[]): string {
  return [
    '<!-- Generated by scripts/make-sprite.ts from src/imagery/svg/. Do not edit by hand: change a drawing and run the script. -->',
    '<template>',
    '  <svg',
    '    class="sprite"',
    '    width="0"',
    '    height="0"',
    '    aria-hidden="true"',
    '    focusable="false"',
    '  >',
    ...sources.map(symbol),
    '  </svg>',
    '</template>',
    '',
  ].join('\n')
}
